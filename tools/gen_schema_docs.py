# Static (no-exec) generator of docs/reference/schemas.md from pymt5/schemas.py + types.py.
import ast, sys
consts = {}
def ev(n):
    if isinstance(n, ast.Constant): return n.value
    if isinstance(n, ast.Name): return consts[n.id]
    if isinstance(n, ast.List): return [ev(e) for e in n.elts]
    if isinstance(n, ast.Dict): return {ev(k): ev(v) for k, v in zip(n.keys, n.values)}
    if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Add): return ev(n.left) + ev(n.right)
    raise ValueError
def load(path):
    for node in ast.parse(open(path).read()).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try: consts[node.targets[0].id] = ev(node.value)
            except Exception: pass
base = sys.argv[1]
for f in ("constants", "schemas", "types"): load(f"{base}/pymt5/{f}.py")
P = {v: k for k, v in consts.items() if k.startswith("PROP_")}
nm = {"PROP_I8":("i8",1),"PROP_I16":("i16",2),"PROP_I32":("i32",4),"PROP_U8":("u8",1),"PROP_U16":("u16",2),"PROP_U32":("u32",4),"PROP_F32":("f32",4),"PROP_F64":("f64",8),"PROP_TIME":("time(FILETIME)",8),"PROP_I64":("i64",8),"PROP_U64":("u64",8),"PROP_STRING":("ascii str",None),"PROP_FIXED_STRING":("utf16le str",None),"PROP_BYTES":("bytes",None)}
out = ["# Schema reference (generated)\n",
       "> Generated by `tools/gen_schema_docs.py` from the pymt5 sources. Do not edit by hand.\n",
       "Offsets are byte offsets inside one record; every integer/float is little endian. "
       "`str` lengths are **bytes** (a UTF-16LE string of length 64 holds 32 characters). "
       "The Rust constants are `crate::schemas::<NAME>_SCHEMA` and `<NAME>_FIELD_NAMES`.\n"]
for n in consts:
    if not (n.endswith("_SCHEMA") or n.endswith("_SCHEMA_EXT")): continue
    sch = consts[n]
    fn = n.replace("_SCHEMA_EXT", "_FIELD_NAMES_EXT").replace("_SCHEMA", "_FIELD_NAMES")
    names = consts.get(fn)
    off = 0; rows = []
    for i, f in enumerate(sch):
        t, sz = nm[P[f["propType"]]]
        size = f.get("propLength") if sz is None else sz
        rows.append(f"| {i} | {names[i] if names else ''} | {t} | {size} | {off} |")
        off += size
    out.append(f"\n## `{n}`  ({len(sch)} fields, {off} bytes)\n")
    out.append("| # | field | type | size | offset |\n|---|---|---|---|---|")
    out += rows
open(sys.argv[2], "w").write("\n".join(out) + "\n")
