# Static (no-exec) converter for pymt5/constants.py integer constants.
import ast, sys
src = open(sys.argv[1] + "/pymt5/constants.py").read()
consts = {}
out = ["// @generated by tools/gen_constants.py from pymt5/constants.py -- do not edit by hand.\n"]
for node in ast.parse(src).body:
    if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
        n = node.targets[0].id
        try: v = ast.literal_eval(node.value)
        except Exception:
            if isinstance(node.value, ast.BinOp): v = eval(compile(ast.Expression(node.value), "x", "eval"), {}, consts)
            else: continue
        consts[n] = v
        if n.startswith("PROP_") or n == "INITIAL_KEY_OBFUSCATED" and False: continue
        if isinstance(v, bool): continue
        if isinstance(v, int):
            ty = "u16" if n.startswith(("CMD_", "PERIOD_")) else "usize" if n in ("HEADER_BYTE_LENGTH", "DEFAULT_TOKEN_LENGTH") else "u32" if n.startswith(("TRADE_RETCODE_", "OUTER_", "COPY_")) else "i64"
            out.append("pub const %s: %s = %d;" % (n, ty, v))
        elif isinstance(v, float): out.append("pub const %s: f64 = %r;" % (n, v))
        elif isinstance(v, str): out.append('pub const %s: &str = "%s";' % (n, v.replace("\\", "\\\\")))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
