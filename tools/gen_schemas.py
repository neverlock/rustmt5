# Static (no-exec) converter: parses pymt5/schemas.py + types.py with ast and emits Rust.
import ast, sys
consts = {}
def ev(n):
    if isinstance(n, ast.Constant): return n.value
    if isinstance(n, ast.Name): return consts[n.id]
    if isinstance(n, ast.List): return [ev(e) for e in n.elts]
    if isinstance(n, ast.Dict): return {ev(k): ev(v) for k, v in zip(n.keys, n.values)}
    if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Add): return ev(n.left) + ev(n.right)
    raise ValueError(ast.dump(n))
def load(path):
    for node in ast.parse(open(path).read()).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try: consts[node.targets[0].id] = ev(node.value)
            except Exception: pass
base = sys.argv[1]
load(base + "/pymt5/constants.py"); load(base + "/pymt5/schemas.py"); load(base + "/pymt5/types.py")
P = {v: k for k, v in consts.items() if k.startswith("PROP_")}
nm = {"PROP_I8":"I8","PROP_I16":"I16","PROP_I32":"I32","PROP_U8":"U8","PROP_U16":"U16","PROP_U32":"U32","PROP_F32":"F32","PROP_F64":"F64","PROP_TIME":"Time","PROP_I64":"I64","PROP_U64":"U64","PROP_STRING":"String","PROP_FIXED_STRING":"FixedString","PROP_BYTES":"Bytes"}
def fmt(s):
    return "\n".join("    Field { ty: PropType::%s, len: %s }," % (nm[P[f["propType"]]], "Some(%d)" % f["propLength"] if f.get("propLength") is not None else "None") for f in s)
o = ["// @generated by tools/gen_schemas.py from pymt5/schemas.py -- do not edit by hand.\n", "use crate::protocol::{Field, PropType};\n"]
for k in ("FULL_SYMBOL_TRADE_CONFIG_LENGTH","FULL_SYMBOL_SCHEDULE_LENGTH","FULL_SYMBOL_SUBSCRIPTION_LENGTH"):
    o.append("pub const %s: usize = %d;" % (k, consts[k]))
for n in consts:
    if n.endswith("_SCHEMA") or n.endswith("_SCHEMA_EXT"):
        o.append("\npub const %s: &[Field] = &[\n%s\n];" % (n, fmt(consts[n])))
        fn = n.replace("_SCHEMA_EXT", "_FIELD_NAMES_EXT").replace("_SCHEMA", "_FIELD_NAMES")
        if fn in consts:
            o.append("pub const %s: &[&str] = &[%s];" % (fn, ", ".join('"%s"' % x for x in consts[fn])))
open(sys.argv[2], "w").write("\n".join(o) + "\n")
